use syscall::kind;

use crate::error::PinsError;

ipc::protocol! {
    /// Выводы узлов устройств, которыми управляет контроллер выводов.
    pub mod pins {
        name = "Pins";

        /// Выдаёт сессию выводов узла `device` и применяет к выводам состояние `default` узла.
        /// Узел и выводы его состояния заняты до ухода клиента сессии.
        call async fn open(
            device: platform_abi::DeviceId,
        ) -> own Result<ipc::wire::Session<crate::device_pins::Protocol>, PinsError>;
    }
}

ipc::protocol! {
    /// Выводы узла устройства, выданные сессии в состоянии `default` узла, и линии узла и его
    /// потомков.
    pub mod device_pins {
        name = "DevicePins";

        /// Переводит во вход вывод линии `index` с именем `name` узла `node` и возвращает номер
        /// линии. Имя линии задаёт биндинг устройства, например `reset`, пустое имя называет
        /// безымянную линию. `node` - узел сессии либо его потомок. Вывод занят до ухода
        /// клиента сессии. Повторный вызов возвращает тот же номер.
        ///
        /// Отказы:
        /// - `NoDevice` - `node` не узел сессии и не его потомок либо у узла нет линии `index` с
        ///   именем `name`;
        /// - `Unsupported` - линию обслуживает другой контроллер, вывод вне контроллера либо
        ///   поставщик не поддерживает флаги линии;
        /// - `Busy` - вывод занят сессией другого узла либо выдан сессии линией-выходом;
        /// - `Denied` - контроллер запретил этой среде исполнения обращение к выводу;
        /// - `NoSpace` - сессии выдано 256 линий;
        /// - `Failed` - контроллер не выполнил чтение либо запись регистров.
        call async fn input(node: platform_abi::DeviceId, name: &str, index: u8) -> Result<u8, PinsError>;

        /// Как `input`, но переводит вывод в выход с уровнем `active`, как у `set`. Уровень
        /// задаётся до включения выхода. Повторный вызов возвращает тот же номер и задаёт уровень.
        ///
        /// Отказы:
        /// - `NoDevice`, `Unsupported`, `NoSpace` - как у `input`;
        /// - `Busy` - вывод занят сессией другого узла либо выдан сессии линией-входом, в том
        ///   числе линией `interrupt`;
        /// - `Denied`, `Failed` - как у `input`.
        call fn output(
            node: platform_abi::DeviceId,
            name: &str,
            index: u8,
            active: bool,
        ) -> Result<u8, PinsError>;

        /// Как `input`, но берёт линию по записи `index` свойства `interrupts-extended` узла
        /// `node`. Прерывание линии срабатывает по условию записи. Повторный вызов возвращает
        /// тот же номер.
        ///
        /// Отказы:
        /// - `NoDevice` - `node` не узел сессии и не его потомок либо у узла нет записи `index`;
        /// - `Unsupported` - запись называет другой контроллер, вывод вне контроллера либо
        ///   условие, которого поставщик не поддерживает;
        /// - `Busy` - вывод занят сессией другого узла либо выдан сессии линией-выходом;
        /// - `Denied`, `NoSpace`, `Failed` - как у `input`.
        call fn interrupt(node: platform_abi::DeviceId, index: u8) -> Result<u8, PinsError>;

        /// Возвращает `true`, если вывод линии `line` на активном уровне. Активный уровень линии
        /// задаёт её описание.
        ///
        /// Отказы:
        /// - `NotIssued` - линия не выдана сессии;
        /// - `Denied`, `Failed` - как у `input`.
        call async fn active(line: u8) -> Result<bool, PinsError>;

        /// Выставляет выходу линии `line` активный уровень, если `active`, и неактивный иначе.
        ///
        /// Отказы:
        /// - `NotIssued` - линия не выдана сессии через `output`;
        /// - `Denied`, `Failed` - как у `input`.
        call fn set(line: u8, active: bool) -> Result<(), PinsError>;

        /// Выдаёт копию `Signal` прерывания линии-входа `line`. Прерывание линии `input`
        /// срабатывает при подъёме и спаде уровня её вывода, линии `interrupt` - по условию её
        /// записи. Срабатывание поднимает `SIGNALED` и запрещает прерывание до `ack`. Уход
        /// клиента сессии запрещает прерывание и отзывает каждую выданную копию.
        ///
        /// Отказы:
        /// - `NotIssued` - линия не выдана сессии как вход;
        /// - `Busy` - на выводе линии выдано прерывание другой линии сессии;
        /// - `NoSpace` - контроллеру не хватает ресурса на `Signal`;
        /// - `Denied`, `Failed` - как у `input`.
        call async fn irq(line: u8) -> own Result<ipc::wire::Cap<kind::Signal>, PinsError>;

        /// Опускает `SIGNALED` прерывания линии `line` и снова разрешает прерывание.
        ///
        /// Отказы:
        /// - `NotIssued` - линия либо её прерывание не выданы сессии;
        /// - `Denied`, `Failed` - как у `input`.
        call async fn ack(line: u8) -> Result<(), PinsError>;
    }
}
