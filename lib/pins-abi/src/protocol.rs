use syscall::kind;

use crate::error::PinsError;

ipc::protocol! {
    /// Выводы узлов устройств, которыми управляет контроллер выводов.
    pub mod pins {
        name = "Pins";

        /// Выдаёт сессию выводов узла, путь которого в описании равен `device`, как путь
        /// `DeviceId` в `Platform`, и применяет к выводам состояние `default` узла. Узел и
        /// выводы его состояния заняты до ухода клиента сессии.
        call fn open(
            device: &str,
        ) -> own Result<ipc::wire::Session<crate::device_pins::Protocol>, PinsError>;
    }
}

ipc::protocol! {
    /// Выводы узла устройства, выданные сессии в состоянии `default` узла, и линии узла и его
    /// потомков.
    pub mod device_pins {
        name = "DevicePins";

        /// Выдаёт номер линии записи `index` свойства `property` узла `node` - узла сессии либо
        /// его потомка - и переводит её вывод во вход. Именем свойства служит `gpios` либо имя с
        /// окончанием `-gpios`. Вывод занят до ухода клиента сессии. Повторный вызов с той же
        /// записью выдаёт тот же номер. Отказ оставляет регистры, записанные до него.
        ///
        /// Отказы:
        /// - `NoDevice` - `node` не узел сессии и не его потомок, имя свойства не описывает
        ///   линии либо в свойстве нет записи `index`;
        /// - `Unsupported` - запись называет контроллер, который поставщик не обслуживает, вывод
        ///   вне контроллера либо флаги кроме `GPIO_ACTIVE_LOW`;
        /// - `Busy` - вывод занят сессией другого узла;
        /// - `Denied` - контроллер запретил этой среде исполнения обращение к выводу;
        /// - `Failed` - контроллер не выполнил чтение либо запись регистров.
        call fn input(node: &str, property: &str, index: u8) -> Result<u8, PinsError>;

        /// Возвращает `true`, если уровень вывода линии `line` высокий, а её запись не
        /// содержит флага `GPIO_ACTIVE_LOW`, либо уровень низкий, а запись содержит этот флаг.
        ///
        /// Отказы:
        /// - `NotIssued` - линия не выдана сессии;
        /// - `Denied`, `Failed` - как у `input`.
        call fn active(line: u8) -> Result<bool, PinsError>;

        /// Выдаёт копию `Signal` прерывания линии `line`, которое срабатывает при подъёме и спаде
        /// уровня её вывода. Срабатывание поднимает `SIGNALED` и запрещает прерывание до `ack`.
        /// Уход клиента сессии запрещает прерывание и отзывает каждую выданную копию.
        ///
        /// Отказы:
        /// - `NotIssued` - линия не выдана сессии;
        /// - `NoSpace` - контроллеру не хватает ресурса на `Signal`;
        /// - `Denied`, `Failed` - как у `input`.
        call fn irq(line: u8) -> own Result<ipc::wire::Cap<kind::Signal>, PinsError>;

        /// Опускает `SIGNALED` прерывания линии `line` и снова разрешает прерывание.
        ///
        /// Отказы:
        /// - `NotIssued` - линия либо её прерывание не выданы сессии;
        /// - `Denied`, `Failed` - как у `input`.
        call fn ack(line: u8) -> Result<(), PinsError>;
    }
}
