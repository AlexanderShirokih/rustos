ipc::wire_enum! {
    /// Отказ операции контракта `Pins`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum PinsError {
        /// Узла нет в описании, он недоступен либо его состояние `default` не содержит наборов
        /// контроллера.
        NoDevice = 1,
        /// Узел либо вывод его состояния занят открытой сессией.
        Busy = 2,
        /// Состояние узла повреждено либо контроллер не может его применить.
        Unsupported = 3,
        /// Состояние называет вывод, закрытый для этой среды исполнения.
        Denied = 4,
        /// Контроллеру не хватает ресурса на сессию.
        NoSpace = 5,
        /// Контроллер не выполнил чтение либо запись регистров вывода.
        Failed = 6,
        /// Линия либо её прерывание не выданы сессии.
        NotIssued = 7,
    }
}
