/// Часы реального времени на сервисном порту драйвера.
#[ipc::protocol(name = "Rtc")]
pub trait Rtc {
    /// Текущее время устройства в секундах.
    #[call]
    fn now(&self) -> u64;

    /// Заводит будильник устройства и возвращает время после его срабатывания.
    #[call]
    fn tick(&self) -> u64;
}
