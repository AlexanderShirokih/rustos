//! Контракт `Rtc` для чтения времени часов реального времени и ожидания их будильника.
//!
//! Клиента и сервис даёт модуль [`rtc`]. Операция `now` отдаёт текущее время устройства в
//! секундах, `tick` ставит будильник и возвращает время его срабатывания.
#![cfg_attr(not(test), no_std)]

ipc::protocol! {
    /// Часы реального времени на сервисном порту драйвера.
    pub mod rtc {
        name = "Rtc";

        /// Текущее время устройства в секундах.
        call fn now() -> u64;

        /// Заводит будильник устройства и возвращает время после его срабатывания.
        call fn tick() -> u64;
    }
}
