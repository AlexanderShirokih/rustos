//! Контракт часов реального времени: чтение времени устройства и ожидание его
//! будильника.
#![cfg_attr(not(test), no_std)]

ipc::protocol! {
    /// Часы реального времени на сервисном порту драйвера.
    pub mod rtc {
        name = "Rtc";

        /// Текущее время устройства в секундах.
        call fn now() -> u64;

        /// Заводит будильник устройства и возвращает время после его срабатывания.
        call fn tick() -> u64;
    }
}
