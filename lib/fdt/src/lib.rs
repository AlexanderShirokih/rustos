//! Читает flattened device tree: узлы, их свойства и зарезервированные диапазоны памяти.
//!
//! [`devicetree::DeviceTree`] строится по адресу блоба либо по срезу его байт и заимствует
//! эти байты. [`devicetree::Node`] даёт свойства узла и его детей,
//! [`devicetree::Property`] переводит значение свойства в число или строку.
//!
//! Разбор идёт без аллокации и без копирования, узел и свойство ссылаются прямо в блоб.
//! Биндинги поверх голого дерева - адресные диапазоны, `ranges`, размеры ячеек - собраны в
//! [`devicetreeext`].

