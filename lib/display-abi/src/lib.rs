//! Объявляет контракт [`display`] вывода изображения на экран и формат поверхности его сессии.
//!
//! Драйвер экспортирует `Display` на каждый свой экран, и клиент получает сессию экрана
//! запросом протокола. Сессия открыта к одному экрану. Клиент рисует в поверхность сессии и
//! вызовом `present` переносит прямоугольник поверхности на экран.
//!
//! Формат поверхности не зависит от экрана. Пиксель занимает [`SURFACE_PIXEL_BYTES`] байта со
//! значением `0xXXRRGGBB` в порядке little-endian. Значение старшего байта `XX` не определено,
//! и сервер переносит его на экран без изменений либо отбрасывает. Шаг строки равен ширине
//! экрана, умноженной на [`SURFACE_PIXEL_BYTES`]. В формат буфера экрана пиксели переводит сервер.

#![cfg_attr(not(test), no_std)]

