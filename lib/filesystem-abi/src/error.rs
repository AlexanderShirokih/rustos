ipc::wire_enum! {
    /// Причина отказа файловой операции.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum FileSystemError {
        /// Узел по указанному пути отсутствует.
        NotFound = 1,
        /// Компонент пути либо сам узел оказался файлом, а операция требует каталога.
        NotADirectory = 2,
        /// Операция над файлом применена к каталогу.
        IsADirectory = 3,
        /// Каталог с записями, а операция требует пустого.
        NotEmpty = 4,
        /// Имя, префикс монтирования либо буфер сессии уже заняты, а операция требует свободного.
        AlreadyExists = 5,
        /// Путь вне границ либо нарушает форму.
        InvalidPath = 6,
        /// Дескриптор не открыт в этой сессии.
        BadDescriptor = 7,
        /// Исчерпан потолок дескрипторов сессии.
        TooManyOpenFiles = 8,
        /// Бекенд не допускает изменений.
        ReadOnly = 9,
        /// Не хватает ресурса под запрошенный объём.
        NoSpace = 10,
        /// Операция пересекает границу точки монтирования.
        CrossMount = 11,
        /// За значком кадра сессия не установлена, либо кадр пришёл по хэндлу без значка.
        NoSession = 12,
        /// Буфер данных сессии не выделен.
        NoBuffer = 13,
        /// Запрошенный объём превышает буфер сессии.
        BufferTooSmall = 14,
        /// Бекенд не поддерживает операцию либо форму переданного ресурса.
        NotSupported = 15,
        /// Файловая система за монтированием не ответила в отведённый срок.
        Unresponsive = 16,
        /// Операция вне режима, в котором открыт дескриптор.
        WrongMode = 17,
    }
}
