ipc::wire_enum! {
    /// Отказ операции контракта `Spmi`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum SpmiError {
        /// Ни в одном списке совместимостей устройств за арбитром нет запрошенной строки либо
        /// шина не работает с арбитром.
        NoDevice = 1,
        /// Каждое устройство с запрошенной строкой в списке совместимостей занято.
        Busy = 2,
        /// Шине не хватает ресурса на сессию устройства.
        NoSpace = 3,
    }
}

ipc::wire_enum! {
    /// Отказ операции контракта `SpmiDevice`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum DeviceError {
        /// Регистры либо прерывание лежат вне блоков устройства, бит прерывания вне 0..=7 либо
        /// число байт вне 1..=8.
        OutOfRange = 1,
        /// Канал блока принадлежит другой среде исполнения.
        Denied = 2,
        /// Арбитр не выполнил команду.
        Failed = 3,
        /// Описание не задаёт запрошенное прерывание для этой шины.
        NotDescribed = 4,
        /// Шина не смогла выдать `Signal` прерывания либо прерывание не выдано сессии.
        Unavailable = 5,
    }
}
