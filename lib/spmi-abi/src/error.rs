ipc::wire_enum! {
    /// Отказ операции контракта `Spmi`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum SpmiError {
        /// Путь не называет устройство за арбитром либо шина не работает с арбитром.
        NoDevice = 1,
        /// Устройство занято сессией другого клиента.
        Busy = 2,
        /// Шине не хватает ресурса на сессию устройства.
        NoSpace = 3,
        /// Узел устройства не задаёт блоки запрошенного числа: у него нет своей единственной
        /// записи `reg`, число блоков равно 0, блок выходит за 0xFF либо принадлежит другому
        /// устройству того же ведомого.
        Range = 4,
    }
}

ipc::wire_enum! {
    /// Отказ операции контрактов `SpmiDevice` и `SpmiInterrupt`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum DeviceError {
        /// Регистры либо прерывание лежат вне блоков устройства, бит прерывания вне 0..=7 либо
        /// число байт вне 1..=8.
        OutOfRange = 1,
        /// Канал блока принадлежит другой среде исполнения.
        Denied = 2,
        /// Арбитр не выполнил команду.
        Failed = 3,
        /// Описание не задаёт запрошенное прерывание для этой шины.
        NotDescribed = 4,
        /// Шина не смогла выдать `Signal` или сессию прерывания либо ушёл клиент сессии
        /// устройства, выдавшей сессию прерывания.
        Unavailable = 5,
        /// Прерывание выдано открытой сессии прерывания.
        Busy = 6,
    }
}
