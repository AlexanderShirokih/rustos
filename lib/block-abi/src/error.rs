ipc::wire_enum! {
    /// Отказ операции контракта `BlockDevice`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum BlockError {
        /// Буфер данных сессии не выделен.
        NoBuffer = 1,
        /// Запрошенные блоки длиннее буфера сессии.
        BufferTooSmall = 2,
        /// Запрошенные блоки выходят за диск.
        OutOfRange = 3,
        /// Сессия уже получила буфер.
        AlreadyExists = 4,
        /// Размер буфера нулевой, больше предела передачи либо серверу не хватает памяти.
        NoSpace = 5,
        /// Устройство ответило ошибкой, не ответило в срок либо находится в отказе.
        Device = 6,
    }
}
