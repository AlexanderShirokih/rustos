//! Сведения о диске.

ipc::wire_value! {
    /// Геометрия диска сессии.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub struct BlockInfo {
        /// Размер блока в байтах: степень двойки не меньше 512.
        pub block_size: u32,
        /// Число блоков диска.
        pub blocks: u64,
        /// Наибольшая длина одного запроса и буфера сессии в байтах. Кратна размеру блока, не
        /// меньше одного блока и не больше 64 KiB.
        pub transfer_max: u32,
    }
}
