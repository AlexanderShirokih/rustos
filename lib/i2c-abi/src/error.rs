ipc::wire_enum! {
    /// Отказ операции контракта `I2c`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum I2cError {
        /// Путь не называет устройство за контроллером шины либо контроллер не готов к работе.
        NoDevice = 1,
        /// Устройство занято сессией.
        Busy = 2,
        /// Шина не работает с адресом устройства.
        Unsupported = 3,
        /// Шине не хватает ресурса на сессию устройства.
        NoSpace = 4,
    }
}

ipc::wire_enum! {
    /// Отказ передачи контракта `I2cDevice`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum TransferError {
        /// Число байт передачи равно 0 либо больше, чем контроллер передаёт за раз.
        Length = 1,
        /// Устройство не подтвердило адрес либо байт.
        NoAck = 2,
        /// Контроллер сообщил об ошибке шины, кроме отсутствия подтверждения.
        Bus = 3,
        /// Контроллер не завершил передачу либо смену состояния за отведённое время.
        Timeout = 4,
    }
}
