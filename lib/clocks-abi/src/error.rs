ipc::wire_enum! {
    /// Отказ операции контракта `Clocks`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum ClocksError {
        /// Узла нет в описании, он недоступен, не называет тактов контроллера либо не занят
        /// этой сессией.
        NoDevice = 1,
        /// Узел занят другой сессией.
        Busy = 2,
        /// Запись тактов узла повреждена, такт вне таблицы контроллера, у такта нет генератора
        /// либо частоты нет в таблице генератора.
        Unsupported = 3,
        /// Ветвь такта не сообщила о работе либо генератор не применил настройку за отведённое
        /// время.
        Timeout = 4,
    }
}
