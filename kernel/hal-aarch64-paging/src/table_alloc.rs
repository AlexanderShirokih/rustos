//! Аллокатор таблиц страниц.

use memory::physical_address::PageAlignedAddress;

use crate::{level::Level, page_table::PageTable};

/// Аллокатор таблиц страниц.
///
/// Отвечает за выделение памяти под новые таблицы и получение
/// указателей на них по физическому адресу.
pub trait TableAlloc {
    /// Выделяет эксклюзивную физическую страницу 4 КБ, доступную через
    /// [`Self::unlinked_table_ptr`].
    fn alloc_table_page(&mut self) -> Option<PageAlignedAddress>;

    /// Возвращает указатель для инициализации выделенной, но ещё не
    /// опубликованной в дереве трансляции таблицы.
    ///
    /// # Safety
    ///
    /// `pa` получен из [`Self::alloc_table_page`] этого аллокатора, не связан
    /// с родительским дескриптором и остаётся в эксклюзивном владении
    /// вызывающего.
    unsafe fn unlinked_table_ptr<L: Level>(&self, pa: PageAlignedAddress) -> *mut PageTable<L>;

    /// Возвращает указатель на таблицу по её физическому адресу.
    ///
    /// `target_va` называет виртуальный адрес, чей путь трансляции ведёт через эту таблицу.
    /// Реализация может учитывать его при выборе отображения PA->VA.
    ///
    /// # Safety
    ///
    /// `pa` указывает на инициализированную таблицу, достижимую через дерево
    /// трансляции. Вызывающий обеспечивает допустимость последующих
    /// разыменований.
    unsafe fn table_ptr<L: Level>(
        &self,
        pa: PageAlignedAddress,
        target_va: usize,
    ) -> *mut PageTable<L>;
}
