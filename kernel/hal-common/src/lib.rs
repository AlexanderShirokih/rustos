//! Разбирает внешние описания платформы и ведёт учёт разобранного: сведения загрузки,
//! топологию процессоров, выбор консоли, словарь PSCI.
//!
//! [`boot`] называет источники описания - блоб device tree, таблицы ACPI, диапазон полезной
//! нагрузки загрузчика. [`cpu`] строит по device tree топологию процессоров и их affinity.
//! [`scanner`] находит назначенную консоль и образ initrd. [`smp`] раскодирует способ вызова
//! PSCI и его коды отказа.
//!
//! Крейт разбирает байты и не обращается к регистрам. `hvc` и `smc`, названные в
//! [`smp::PsciConduit`] значениями свойства `method`, исполняет крейт архитектуры. Разбор
//! device tree и решения о подъёме процессоров покрыты обычными тестами на host.

#![cfg_attr(not(test), no_std)]

pub mod boot;
pub mod cpu;
pub mod scanner;
pub mod smp;
